/**
 * deploy.js
 * Deploys MediChain.sol to the configured network.
 * After deployment, writes the address + ABI to:
 *   /frontend/src/contract/index.js
 *   /backend/src/contract/index.js
 *
 * Run: npx hardhat run scripts/deploy.js --network mst
 */

const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

const EXPLORER_BASE = "https://testnet.mstscan.com";

async function main() {
  console.log("━".repeat(60));
  console.log("  MediChain — Deployment");
  console.log("━".repeat(60));

  const [deployer] = await ethers.getSigners();
  const network = await ethers.provider.getNetwork();

  console.log(`\n🌐 Network  : ${network.name} (chainId ${network.chainId})`);
  console.log(`📤 Deployer : ${deployer.address}`);

  const balance = await ethers.provider.getBalance(deployer.address);
  console.log(`💳 Balance  : ${ethers.formatEther(balance)} MSTC`);

  if (balance === 0n) {
    console.error("\n❌ Deployer has 0 MSTC — cannot deploy. Fund it first:");
    console.error("   https://faucet.mstblockchain.com/");
    process.exit(1);
  }

  console.log("\n🚀 Deploying MediChain...");
  const MediChain = await ethers.getContractFactory("MediChain");

  // The deployer becomes the DEFAULT_ADMIN_ROLE holder (can grant other roles)
  const medichain = await MediChain.deploy(deployer.address);
  await medichain.waitForDeployment();

  const address = await medichain.getAddress();
  const deployTx = medichain.deploymentTransaction();

  console.log(`\n✅ MediChain deployed at : ${address}`);
  console.log(`   Deploy TX             : ${deployTx?.hash}`);
  console.log(`   Explorer (contract)   : ${EXPLORER_BASE}/address/${address}`);
  console.log(`   Explorer (tx)         : ${EXPLORER_BASE}/tx/${deployTx?.hash}`);

  // ─── Write artifacts to frontend and backend ───────────────────────────────

  const artifact = await ethers.getContractFactory("MediChain");
  // Get the ABI from the compiled artifact
  const compiledArtifact = require(
    path.join(__dirname, "..", "artifacts", "contracts", "MediChain.sol", "MediChain.json")
  );
  const abi = compiledArtifact.abi;

  const contractInfo = {
    address,
    chainId: network.chainId.toString(),
    deployTxHash: deployTx?.hash,
    deployedAt: new Date().toISOString(),
    abi,
  };

  // Paths relative to this script (contracts/scripts/deploy.js)
  const contractsRoot = path.join(__dirname, "..");
  const monoRoot = path.join(contractsRoot, "..");

  const targets = [
    path.join(monoRoot, "frontend", "src", "contract"),
    path.join(monoRoot, "backend",  "src", "contract"),
  ];

  for (const dir of targets) {
    fs.mkdirSync(dir, { recursive: true });

    // Write as JS module so both React and Node.js can import it
    const content = `// Auto-generated by deploy.js — DO NOT EDIT MANUALLY
// Deployed at: ${contractInfo.deployedAt}

export const CONTRACT_ADDRESS = "${address}";
export const CHAIN_ID = ${network.chainId};
export const DEPLOY_TX_HASH = "${deployTx?.hash}";

export const ABI = ${JSON.stringify(abi, null, 2)};

export default { CONTRACT_ADDRESS, CHAIN_ID, ABI };
`;
    fs.writeFileSync(path.join(dir, "index.js"), content);

    // Also write a JSON file for Node.js require() compatibility
    fs.writeFileSync(
      path.join(dir, "contract.json"),
      JSON.stringify(contractInfo, null, 2)
    );

    console.log(`\n📁 Written to: ${dir}`);
  }

  console.log("\n━".repeat(60));
  console.log("  ✅ Deployment complete!");
  console.log(
    `\n  🔗 ${EXPLORER_BASE}/address/${address}`
  );
  console.log("━".repeat(60));
}

main().catch((err) => {
  console.error("Deployment failed:", err);
  process.exit(1);
});
